package com.aistudio.netgate.selftest

import android.content.Context
import com.aistudio.netgate.BuildConfig
import com.aistudio.netgate.service.CrashLogRecorder
import org.json.JSONArray
import org.json.JSONObject

/** Device/app identity shown at the top of every report. */
data class SelfTestReportMetadata(
    val appVersion: String,
    val versionCode: Int,
    val buildType: String,
    val gitCommitSha: String,
    val isMinified: Boolean,
    val androidApi: Int,
    val deviceModel: String,
    val generatedAtMs: Long,
    val latestCrashHeadline: String? = null
) {
    companion object {
        fun current(
            context: Context? = null,
            nowMs: Long = System.currentTimeMillis()
        ): SelfTestReportMetadata {
            val crashHeadline = context?.let { ctx ->
                CrashLogRecorder.reports(ctx).firstOrNull()?.headline
            }
            return SelfTestReportMetadata(
                appVersion = BuildConfig.VERSION_NAME,
                versionCode = BuildConfig.VERSION_CODE,
                buildType = BuildConfig.BUILD_TYPE,
                gitCommitSha = BuildConfig.GIT_COMMIT_SHA,
                isMinified = !BuildConfig.DEBUG,
                androidApi = android.os.Build.VERSION.SDK_INT,
                deviceModel = android.os.Build.MODEL.orEmpty(),
                generatedAtMs = nowMs,
                latestCrashHeadline = crashHeadline
            )
        }
    }
}

/**
 * Builds the Markdown and JSON self-test report.
 *
 * Privacy: log lines are redacted before they enter a report — IP addresses, hostnames and
 * package names become placeholders, so a shared report never reveals what the device browsed or
 * which apps are installed. Test messages and details are generated by NetGate itself and carry
 * synthetic `.test` names or counts only.
 */
object SelfTestReport {

    private val IPV4 = Regex("\\b(?:\\d{1,3}\\.){3}\\d{1,3}\\b")
    // Require a real IPv6 shape: a full 8-group address or a `::` compressed form. A bare
    // HH:mm:ss / HH:mm:ss.SSS timestamp has only two colons and must not be redacted as an IP.
    private val IPV6 = Regex(
        "(?i)\\b(?:[0-9a-f]{1,4}:){7}[0-9a-f]{1,4}\\b|" +
            "\\b(?:[0-9a-f]{0,4}:){2,}:[0-9a-f]{0,4}\\b|" +
            "\\b::(?:[0-9a-f]{1,4}:){0,6}[0-9a-f]{1,4}\\b"
    )
    // A hyphenated prefix (e.g. "amazon-tam-") must not let the trailing dotted suffix be
    // redacted on its own, leaving "amazon-tam-<package>" behind.
    private val PACKAGE_NAME = Regex("(?<!-)\\b(?:[A-Za-z][A-Za-z0-9_]*\\.){2,}[A-Za-z][A-Za-z0-9_]*\\b")
    private val HOSTNAME = Regex(
        "\\b(?:[a-z0-9](?:[a-z0-9-]{0,61}[a-z0-9])?\\.)+[a-z]{2,24}\\b",
        RegexOption.IGNORE_CASE
    )

    private val ALLOWED_PACKAGE_PREFIXES = listOf(
        "com.aistudio.netgate.",
        "java.",
        "kotlin.",
        "android."
    )

    private fun isAllowedPackage(value: String): Boolean =
        ALLOWED_PACKAGE_PREFIXES.any { prefix -> value == prefix.trimEnd('.') || value.startsWith(prefix) }

    private fun isAllowedHost(value: String): Boolean {
        val lower = value.lowercase()
        if (lower == "localhost" || lower.contains("netgate")) return true
        // Never redact source-file names that appear in stack traces.
        if (value != lower) return true
        if (lower.endsWith(".kt") || lower.endsWith(".java") || lower.endsWith(".class")) return true
        return false
    }

    /** Replaces anything that could identify a site, resolver or installed app. */
    fun redact(text: String): String = text
        .replace(IPV4) { "<ip>" }
        .replace(IPV6) { "<ip>" }
        .replace(PACKAGE_NAME) { match ->
            if (isAllowedPackage(match.value)) match.value else "<package>"
        }
        .replace(HOSTNAME) { match ->
            if (isAllowedHost(match.value)) match.value else "<host>"
        }

    fun markdown(
        metadata: SelfTestReportMetadata,
        results: List<TestResult>,
        logLines: List<String> = emptyList()
    ): String {
        val summary = TestSummary.of(results)
        return buildString {
            appendLine("# NetGate Self-Test Report")
            appendLine()
            appendLine("| Field | Value |")
            appendLine("| --- | --- |")
            appendLine("| App | ${metadata.appVersion} (${metadata.versionCode}) |")
            appendLine("| Build | ${metadata.buildType} |")
            appendLine("| Git commit | ${metadata.gitCommitSha.ifBlank { "unknown" }} |")
            appendLine("| Minified | ${metadata.isMinified} |")
            appendLine("| Latest crash | ${metadata.latestCrashHeadline ?: "none"} |")
            appendLine("| Android API | ${metadata.androidApi} |")
            appendLine("| Device | ${metadata.deviceModel.ifBlank { "unknown" }} |")
            appendLine("| Generated | ${formatTimestamp(metadata.generatedAtMs)} |")
            appendLine(
                "| Summary | ${summary.total} tests — ${summary.pass} pass, " +
                    "${summary.fail} fail, ${summary.warn} warn, ${summary.skip} skip |"
            )
            appendLine()

            for ((group, groupResults) in results.groupBy { it.group }) {
                appendLine("## $group")
                appendLine()
                for (result in groupResults) {
                    appendLine(
                        "- **${statusLabel(result.status)} ${result.name}** " +
                            "(${result.durationMs} ms) — ${result.message}"
                    )
                    result.detail?.takeIf { it.isNotBlank() }?.let { detail ->
                        appendLine("  ```")
                        detail.lineSequence().forEach { line -> appendLine("  $line") }
                        appendLine("  ```")
                    }
                }
                appendLine()
            }

            if (logLines.isNotEmpty()) {
                appendLine("## Recent NetGate log")
                appendLine()
                appendLine("```")
                logLines.forEach { line -> appendLine(redact(line)) }
                appendLine("```")
            }
        }
    }

    fun json(
        metadata: SelfTestReportMetadata,
        results: List<TestResult>,
        logLines: List<String> = emptyList()
    ): String {
        val summary = TestSummary.of(results)
        val root = JSONObject()
        root.put("format", "netgate_selftest_report")
        root.put("schemaVersion", 1)
        root.put("appVersion", metadata.appVersion)
        root.put("versionCode", metadata.versionCode)
        root.put("buildType", metadata.buildType)
        root.put("gitCommitSha", metadata.gitCommitSha)
        root.put("isMinified", metadata.isMinified)
        root.put("latestCrashHeadline", metadata.latestCrashHeadline ?: "")
        root.put("androidApi", metadata.androidApi)
        root.put("deviceModel", metadata.deviceModel)
        root.put("generatedAt", metadata.generatedAtMs)
        root.put(
            "summary",
            JSONObject()
                .put("total", summary.total)
                .put("pass", summary.pass)
                .put("fail", summary.fail)
                .put("warn", summary.warn)
                .put("skip", summary.skip)
        )
        val resultsArray = JSONArray()
        for (result in results) {
            resultsArray.put(
                JSONObject()
                    .put("id", result.id)
                    .put("group", result.group)
                    .put("name", result.name)
                    .put("status", result.status.name)
                    .put("durationMs", result.durationMs)
                    .put("message", result.message)
                    .put("detail", result.detail ?: "")
            )
        }
        root.put("results", resultsArray)
        val logsArray = JSONArray()
        logLines.forEach { line -> logsArray.put(redact(line)) }
        root.put("logs", logsArray)
        return root.toString(2)
    }

    /** Plain text for the "copy failures only" button. */
    fun failuresOnly(results: List<TestResult>): String {
        val failing = results.filter { it.isFailing }
        if (failing.isEmpty()) return "No failures or warnings."
        return buildString {
            for (result in failing) {
                appendLine("${statusLabel(result.status)} [${result.group}] ${result.name} — ${result.message}")
                result.detail?.takeIf { it.isNotBlank() }?.lineSequence()?.take(6)?.forEach { line ->
                    appendLine("    $line")
                }
            }
        }.trimEnd()
    }

    fun statusLabel(status: TestStatus): String = when (status) {
        TestStatus.PASS -> "PASS"
        TestStatus.FAIL -> "FAIL"
        TestStatus.WARN -> "WARN"
        TestStatus.SKIP -> "SKIP"
    }

    private fun formatTimestamp(epochMs: Long): String =
        java.text.SimpleDateFormat("yyyy-MM-dd HH:mm:ss", java.util.Locale.US)
            .format(java.util.Date(epochMs))
}
